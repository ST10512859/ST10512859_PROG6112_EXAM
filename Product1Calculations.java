package za.edu.myemeris.st10512859.prog6112exam;

public class Product1Calculations implements IProduct1Calculations {

    private double price;

    public Product1Calculations(double price) {
        this.price = price;
    }

    @Override
    public double GetVat() {
        return price * 0.15;
    }

    @Override
    public double GetCommission() {
        return price * 0.05;
    }

    @Override
    public double GetTotal() {
        return price + GetVat() + GetCommission();
    }
}
